// This file implements the remaining schemas.Provider methods that llama.cpp's
// llama-server does not support. Each returns an explicit
// unsupported_operation error so Bifrost core can fall back or surface a clear
// message — mirroring the ollama provider's pattern.

// Compaction is not supported by the llama.cpp provider.
func (provider *LLamaCppProvider) Compaction(ctx *schemas.BifrostContext, key schemas.Key, request *schemas.BifrostCompactionRequest) (*schemas.BifrostCompactionResponse, *schemas.BifrostError) {
	return nil, providerUtils.NewUnsupportedOperationError(schemas.CompactionRequest, provider.GetProviderKey())
}

